#!/usr/bin/env python3
"""Regenerate src/tokens.rs from microsoft-ui-xaml's Common_themeresources_any.xaml.

Usage: gen_tokens.py <Common_themeresources_any.xaml> <commit-sha> > src/tokens.rs
"""
import re
import sys
import xml.etree.ElementTree as ET

X = "{http://schemas.microsoft.com/winfx/2006/xaml}"
P = "{http://schemas.microsoft.com/winfx/2006/xaml/presentation}"

# Brushes whose colour comes from the accent ramp, per theme (WinUI resource -> ramp step, opacity).
ACCENT = {
    "Dark": {
        "AccentTextFillColorPrimary": ("light3", 1.0),
        "AccentTextFillColorSecondary": ("light3", 1.0),
        "AccentTextFillColorTertiary": ("light2", 1.0),
        "AccentFillColorSelectedTextBackground": ("base", 1.0),
        "AccentFillColorDefault": ("light2", 1.0),
        "AccentFillColorSecondary": ("light2", 0.9),
        "AccentFillColorTertiary": ("light2", 0.8),
        "SystemFillColorAttention": ("light2", 1.0),
    },
    "Light": {
        "AccentTextFillColorPrimary": ("dark2", 1.0),
        "AccentTextFillColorSecondary": ("dark3", 1.0),
        "AccentTextFillColorTertiary": ("dark1", 1.0),
        "AccentFillColorSelectedTextBackground": ("base", 1.0),
        "AccentFillColorDefault": ("dark1", 1.0),
        "AccentFillColorSecondary": ("dark1", 0.9),
        "AccentFillColorTertiary": ("dark1", 0.8),
        "SystemFillColorAttention": ("base", 1.0),
    },
}
GRADIENTS = ["ControlElevationBorder", "CircleElevationBorder", "AccentControlElevationBorder"]


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def argb(hexstr):
    h = hexstr.lstrip("#")
    if len(h) == 6:
        h = "FF" + h
    return int(h, 16)


def parse(path):
    root = ET.parse(path).getroot()
    themes = {}
    for d in root.find(P + "ResourceDictionary.ThemeDictionaries"):
        key = d.get(X + "Key")
        if key not in ("Default", "Light"):
            continue
        colors, grads = {}, {}
        for el in d:
            k = el.get(X + "Key")
            if el.tag == P + "Color":
                colors[k] = argb(el.text.strip())
            elif el.tag == P + "LinearGradientBrush":
                name = k.removesuffix("Brush")
                flip = el.find(f"{P}LinearGradientBrush.RelativeTransform/{P}ScaleTransform") is not None
                stops = []
                for s in el.find(P + "LinearGradientBrush.GradientStops"):
                    ref = re.match(r"\{StaticResource (\w+)\}", s.get("Color")).group(1)
                    stops.append((float(s.get("Offset")), ref))
                stops.sort(key=lambda st: st[0])  # XAML renders stops in offset order
                grads[name] = dict(
                    absolute=el.get("MappingMode") == "Absolute",
                    end=el.get("EndPoint"),
                    flip=flip,
                    stops=stops,
                )
        themes["Dark" if key == "Default" else "Light"] = (colors, grads)
    return themes


def lit(v):
    return f"Color::from_argb(0x{v:08X})"


def f32(v):
    s = repr(float(v))
    return s


def main():
    path, sha = sys.argv[1], sys.argv[2]
    themes = parse(path)
    dark_c, _ = themes["Dark"]
    light_c, _ = themes["Light"]
    keys = [k for k in dark_c if k in light_c]
    missing = (set(dark_c) ^ set(light_c))
    if missing:
        print(f"// keys only in one theme (skipped): {sorted(missing)}", file=sys.stderr)
    accent_keys = list(ACCENT["Dark"].keys())

    o = []
    w = o.append
    w("// @generated by tools/gen_tokens.py — do not edit by hand.")
    w("// Source: microsoft/microsoft-ui-xaml@" + sha)
    w("//         controls/dev/CommonStyles/Common_themeresources_any.xaml")
    w("// (\"Default\" dictionary = dark, \"Light\" dictionary = light; MIT, (c) Microsoft.)")
    w("")
    w("use crate::accent::AccentRamp;")
    w("use crate::color::Color;")
    w("use crate::gradient::{GradientMapping, LinearGradient};")
    w("use crate::theme::ThemeMode;")
    w("")
    w("/// The Fluent token surface: every `Color` resource of WinUI's common theme")
    w("/// dictionary, plus the accent-derived brushes and the elevation-border gradients.")
    w("/// Field names are the WinUI resource names in snake_case (`Brush` suffix dropped).")
    w("#[derive(Clone, Debug, PartialEq)]")
    w("#[cfg_attr(feature = \"serde\", derive(serde::Serialize, serde::Deserialize))]")
    w("pub struct Tokens {")
    for k in keys:
        w(f"    /// `{k}`")
        w(f"    pub {snake(k)}: Color,")
    w("")
    w("    // Accent-derived (`{ThemeResource SystemAccentColor*}` brushes).")
    for k in accent_keys:
        dk, do = ACCENT["Dark"][k]
        lk, lo = ACCENT["Light"][k]
        def desc(step, op):
            n = "SystemAccentColor" + ("" if step == "base" else step.capitalize())
            return n + (f" @ {op}" if op != 1.0 else "")
        w(f"    /// `{k}` — dark: {desc(dk, do)}; light: {desc(lk, lo)}")
        w(f"    pub {snake(k)}: Color,")
    w("")
    w("    // Elevation borders (`LinearGradientBrush` resources).")
    for g in GRADIENTS:
        w(f"    /// `{g}Brush`")
        w(f"    pub {snake(g)}: LinearGradient,")
    w("}")
    w("")
    w("impl Tokens {")
    w("    /// Resolve the token set for `mode` against an accent ramp.")
    w("    pub fn resolve(mode: ThemeMode, accent: &AccentRamp) -> Self {")
    w("        match mode {")
    w("            ThemeMode::Dark => dark(accent),")
    w("            ThemeMode::Light => light(accent),")
    w("        }")
    w("    }")
    w("")
    w("    /// Every token as `(WinUI resource name, colour)`, for lookup by name and dumps.")
    w("    /// Gradient tokens are not included.")
    w("    pub fn named(&self) -> [(&'static str, Color); %d] {" % (len(keys) + len(accent_keys)))
    w("        [")
    for k in keys + accent_keys:
        w(f"            (\"{k}\", self.{snake(k)}),")
    w("        ]")
    w("    }")
    w("}")
    w("")
    for theme, fn in (("Dark", "dark"), ("Light", "light")):
        colors, grads = themes[theme]
        w(f"fn {fn}(accent: &AccentRamp) -> Tokens {{")
        w("    Tokens {")
        for k in keys:
            w(f"        {snake(k)}: {lit(colors[k])},")
        for k in accent_keys:
            step, op = ACCENT[theme][k]
            expr = f"accent.{step}"
            if op != 1.0:
                expr += f".with_opacity({f32(op)})"
            w(f"        {snake(k)}: {expr},")
        for g in GRADIENTS:
            gd = grads[g]
            ex, ey = (float(v) for v in gd["end"].split(","))
            mapping = (
                f"GradientMapping::Absolute {{ end_x: {f32(ex)}, end_y: {f32(ey)} }}"
                if gd["absolute"] else "GradientMapping::Relative"
            )
            stops = ", ".join(f"({f32(off)}, {lit(colors[ref])})" for off, ref in gd["stops"])
            w(f"        {snake(g)}: LinearGradient {{")
            w(f"            mapping: {mapping},")
            w(f"            flip_y: {str(gd['flip']).lower()},")
            w(f"            stops: [{stops}],")
            w("        },")
        w("    }")
        w("}")
        w("")
    sys.stdout.write("\n".join(o).rstrip() + "\n")


if __name__ == "__main__":
    main()
