#!/usr/bin/env python3
"""Regenerate ../src/generated.rs from microsoft/fluentui-system-icons.

Needs network + `pip install cairosvg` (used only to check that the merged
path renders identically under the fill rule we report). The output is
committed; the crate never touches the network at build time.

    python3 tools/gen.py
"""
import io, json, os, re, sys, urllib.parse, urllib.request

REV = "a3de63245b4fa49c30e20d9838593a105affe774"  # fluentui-system-icons main
RAW = f"https://raw.githubusercontent.com/microsoft/fluentui-system-icons/{REV}/assets"
HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(os.environ.get("XDG_CACHE_HOME", os.path.expanduser("~/.cache")), "winui-icons", REV)
SIZE = 24

def fetch(asset, style):
    snake = asset.lower().replace(" ", "_")
    name = f"ic_fluent_{snake}_{SIZE}_{style}.svg"
    path = os.path.join(CACHE, name)
    if not os.path.exists(path):
        url = f"{RAW}/{urllib.parse.quote(asset)}/SVG/{name}"
        try:
            data = urllib.request.urlopen(url).read()
        except Exception as e:
            sys.exit(f"{asset} ({style}): {url}: {e}")
        os.makedirs(CACHE, exist_ok=True)
        open(path, "wb").write(data)
    return open(path).read()

def paths_of(svg):
    if re.search(r"<(circle|rect|ellipse|line|polygon|polyline|g|use)\b", svg) or "transform" in svg:
        raise ValueError("unsupported SVG element")
    ds = re.findall(r'<path\b[^>]*\bd="([^"]+)"', svg)
    rules = set(re.findall(r'fill-rule="([^"]+)"', svg))
    return ds, rules

def render(d_list, rule):
    import cairosvg
    from PIL import Image
    body = "".join(f'<path d="{d}" fill="#000" fill-rule="{rule}"/>' for d in d_list)
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 24 24">{body}</svg>'
    png = cairosvg.svg2png(bytestring=svg.encode())
    return Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A")

def differs(a, b):
    from PIL import ImageChops
    hist = ImageChops.difference(a, b).histogram()
    return sum(hist[32:])  # pixels whose coverage differs noticeably

def main():
    segoe = json.load(open(os.path.join(HERE, "segoe-fluent-icons.json")))
    rows = []
    for line in open(os.path.join(HERE, "symbols.txt")):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        variant, asset, style, sname = [s.strip() for s in line.split("|")]
        svg = fetch(asset, style)
        ds, rules = paths_of(svg)
        assert ds, asset
        orig_rule = rules.pop() if len(rules) == 1 else "nonzero"
        assert not rules, f"{asset}: mixed fill rules"
        reference = render(ds, orig_rule)
        merged = " ".join(ds)
        if differs(render([merged], "evenodd"), reference) == 0:
            rule = "EvenOdd"
        elif differs(render([merged], "nonzero"), reference) == 0:
            rule = "NonZero"
        else:
            sys.exit(f"{asset}: merged path matches neither fill rule")
        cp = None
        if sname != "-":
            if sname not in segoe:
                sys.exit(f"{variant}: unknown Segoe Fluent Icons name {sname}")
            cp = segoe[sname]
        rows.append((variant, asset, style, merged, rule, sname, cp))

    names = [r[0] for r in rows]
    assert len(names) == len(set(names)), "duplicate variant"
    out = []
    w = out.append
    w("// @generated by tools/gen.py from microsoft/fluentui-system-icons")
    w(f"// rev {REV}, {SIZE}px set. MIT licensed, see LICENSE-fluentui-system-icons.")
    w("// Do not edit by hand.\n")
    w("use crate::FillRule;\n")
    w("/// A Fluent System Icons glyph.")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]")
    w("pub enum Symbol {")
    for v, a, s, *_ in rows:
        w(f"    /// Fluent `{a}` ({s}).")
        w(f"    {v},")
    w("}\n")
    w("impl Symbol {")
    w("    /// Every symbol, in declaration order.")
    w("    pub const ALL: &'static [Symbol] = &[")
    for v in names:
        w(f"        Symbol::{v},")
    w("    ];\n")
    w("    /// Rust variant name, e.g. `\"ChevronDown\"`.")
    w("    pub const fn name(self) -> &'static str {")
    w("        match self {")
    for v in names:
        w(f'            Symbol::{v} => "{v}",')
    w("        }\n    }\n")
    w("    /// Source asset in fluentui-system-icons, e.g. `(\"Chevron Down\", Style::Regular)`.")
    w("    pub const fn fluent_asset(self) -> (&'static str, crate::Style) {")
    w("        match self {")
    for v, a, s, *_ in rows:
        w(f'            Symbol::{v} => ("{a}", crate::Style::{s.capitalize()}),')
    w("        }\n    }\n")
    w("    /// SVG path data in a 24x24 viewBox.")
    w("    pub const fn path(self) -> &'static str {")
    w("        match self {")
    for v, a, s, d, *_ in rows:
        w(f'            Symbol::{v} => "{d}",')
    w("        }\n    }\n")
    w("    /// Fill rule [`Symbol::path`] must be filled with.")
    w("    pub const fn fill_rule(self) -> FillRule {")
    w("        match self {")
    for v, a, s, d, rule, *_ in rows:
        w(f"            Symbol::{v} => FillRule::{rule},")
    w("        }\n    }\n")
    w("    /// Matching Segoe Fluent Icons codepoint, where Windows has an equivalent glyph.")
    w("    pub const fn segoe_codepoint(self) -> Option<char> {")
    w("        match self {")
    for v, a, s, d, rule, sname, cp in rows:
        if cp:
            w(f"            Symbol::{v} => Some('\\u{{{cp}}}'), // {sname}")
    w("            _ => None,")
    w("        }\n    }")
    w("}")
    open(os.path.join(HERE, "..", "src", "generated.rs"), "w").write("\n".join(out) + "\n")
    nz = sum(r[4] == "NonZero" for r in rows)
    print(f"{len(rows)} symbols, {nz} need nonzero, {sum(1 for r in rows if r[6])} with Segoe codepoints")

main()
